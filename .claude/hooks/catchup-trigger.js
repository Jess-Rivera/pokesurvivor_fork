#!/usr/bin/env node
// UserPromptSubmit hook: when the prompt starts with "catch me up" or "catch up", run tools/catchup.js and hand the
// briefing to the assistant as context, so the answer needs no file reads or extra tool calls.
// Any other prompt, or any failure, adds nothing (exit 0).
const cp = require('child_process'),
  path = require('path');
const { readInput, projectDir, logEvent, addContext, cutWithNote } = require('./lib');

const BRIEFING_LIMIT_CHARS = 9000;
const FULL_BRIEFING_FILE = 'catchup-latest.md'; // written by tools/catchup.js

const CATCH_UP_PROMPT = /^\s*(please\s+)?catch\s*(me\s*)?up\b/i;

try {
  const input = readInput();
  if (CATCH_UP_PROMPT.test(input.prompt || '')) {
    const root = projectDir(input);
    const result = cp.spawnSync('node', [path.join(root, 'tools', 'catchup.js')], {
      cwd: root,
      encoding: 'utf8',
      timeout: 90000,
      maxBuffer: 16 * 1024 * 1024,
    });
    if (result.status === 0 && result.stdout) {
      logEvent('catchup-trigger', 'fired', 'briefing ' + result.stdout.length + ' chars');
      addContext(
        'UserPromptSubmit',
        'The catch-up briefing was just generated by tools/catchup.js (do not run it again). Relay it, adding a line or two of ' +
          'judgment (which items first, which drift matters).\n\n' +
          cutWithNote(result.stdout, BRIEFING_LIMIT_CHARS, FULL_BRIEFING_FILE),
      );
    } else {
      logEvent('catchup-trigger', 'failed', String(result.error || result.stderr || result.status).slice(0, 120));
    }
  }
} catch (error) {
  // fail open
}
process.exit(0);
