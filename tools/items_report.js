// tools/items_report.js: regenerates docs/ITEMS.md (every item, what it does, where it drops, how often) from the live data.
// Usage from the repo root:  node tools/items_report.js         (writes docs/ITEMS.md)
//                            node tools/items_report.js --check (exit 1 if docs/ITEMS.md is out of date)
// Reads data/items.js, data/ground-items.js and data/drops.js with stubbed engine globals. Edit the data, then re-run this.
const fs = require('fs'),
  vm = require('vm'),
  path = require('path');
const root = path.resolve(__dirname, '..');
const noop = new Proxy(function () {}, { get: () => noop, apply: () => undefined, construct: () => ({}) });
global.window = global;
global.location = { search: '?dev' };
global.G = new Proxy({}, { get: (t, k) => (k in t ? t[k] : noop), set: (t, k, v) => ((t[k] = v), true) });
G.U = { rand: (a) => a, pick: (a) => a[0], TYPE_COLOR: {} };
for (const p of [
  'js/systems/stages.js',
  'js/data/pokesprite-index.js',
  'js/data/items.js',
  'js/data/ground-items.js',
  'js/data/drops.js',
])
  vm.runInThisContext(fs.readFileSync(path.join(root, p), 'utf8'), { filename: p });

const K = G.Drops.K,
  T = G.Drops.TABLES;
const txt = (s) =>
  String(s || '')
    .replace(/—/g, ',')
    .replace(/\|/g, '/');
const pct = (x) => {
  const v = x * 100;
  return (v >= 10 ? v.toFixed(1) : v >= 1 ? v.toFixed(2) : v.toFixed(3)).replace(/\.?0+$/, '') + '%';
};
const row = (...c) => '| ' + c.map(txt).join(' | ') + ' |';

const poke = G.Items.LIST.filter((i) => i.tier === 'pokemon'),
  run = G.Items.LIST.filter((i) => i.tier === 'run'),
  ground = G.Grounds.LIST;
const nP = poke.length,
  nR = run.length;
const eliteItem = T.elite.find((e) => e.pickup === 'item').p;
const bossRun = T.boss.find((e) => e.pickup === 'item').run,
  gymRun = T.gym.find((e) => e.pickup === 'item').run;
const wildGroundBase = K.groundBase;
// Direct (named) ground drops: entries with a fixed item id in a source table, possibly inside a oneOf.
const flat = (tbl) => tbl.flatMap((e) => e.oneOf || [e]);
const direct = (src, id) =>
  flat(T[src])
    .filter((e) => e.pickup === 'ground' && e.value === id)
    .reduce((a, e) => a + e.p, 0);

const out = [];
out.push('# ITEMS, every item in the game, what it does, where it drops, how often');
out.push('');
out.push(
  'GENERATED by `node tools/items_report.js` from js/data/items.js, ground-items.js and drops.js. Do not edit by hand: change the data, then re-run it.'
);
out.push(
  'Drop chances and sources are owned by js/data/drops.js (one table per source). Rates below are per drop event, computed at the start of a run.'
);
out.push('');
out.push('## How items reach you');
out.push('');
out.push(
  '- **Ground items** (' +
    ground.length +
    '): activate the moment the active Pokemon touches them (status berries go in a small bag instead). Nothing is stored otherwise.'
);
out.push(
  '- **Pokemon items** (' +
    nP +
    '): one held per Pokemon, effect only while that Pokemon is the active one. A found one goes to the active Pokemon.'
);
out.push(
  '- **Run items** (' +
    nR +
    ', shown to the player as team items): shared by the whole team for the run, kept in run slots (1 at the start, up to ' +
    G.Items.RUN_SLOTS_MAX +
    ' bought). A run item dropped in a run is also unlocked for good. Lucky Egg and Amulet Coin start unlocked; any other costs ' +
    G.Items.TEAM_ITEM_PRICE.toLocaleString('en-US') +
    ' PokeCoins in the Shop.'
);
out.push('');
out.push('## Drop sources');
out.push('');
out.push(row('Source', 'What it drops'));
out.push(row('---', '---'));
const gymP = (1 - gymRun) / nP;
const chestItem = T.chest.find((e) => e.pickup === 'item').p,
  bigItem = T.bigchest.find((e) => e.pickup === 'item').p;
out.push(
  row(
    'Wild kill',
    'Ground item ' +
      pct(wildGroundBase) +
      ' (plus the live Pinap bonus), then one shared roll for Oran Berry 0.2%, Sitrus Berry 0.1%, magnet 0.4%, bomb 0.1%, plus x2 ticket 1 in 400, plus XP'
  )
);
out.push(
  row(
    'Elite',
    'Guaranteed heal berry (Oran or Sitrus, 50/50), one guaranteed ground item roll, ' +
      pct(eliteItem) +
      ' chance of a Pokemon item, big XP burst'
  )
);
out.push(
  row(
    'Boss',
    '10 coins, one guaranteed item (' +
      pct(bossRun) +
      ' it is a run item, else a Pokemon item), and the wild extras above'
  )
);
out.push(
  row(
    'Gym leader',
    '10 coins, one guaranteed item (' +
      pct(gymRun) +
      ' it is a run item, else a Pokemon item). No XP, the badge pays a level'
  )
);
out.push(row('Golden enemy', pct(K.golden) + ' for 3 extra coins'));
out.push(row('Meowth (thief)', '20 coins'));
out.push(row('Gholdengo (thief)', '6 coins and an x10 ticket'));
out.push(row('Lost-Pokemon event', '12 coins and a ticket'));
out.push(row('Grass', 'One shared roll: Oran Berry 5%, 1 coin 6%'));
out.push(
  row('Rock', 'One shared roll: small XP orb (1% of the next level) 40%, 2 coins 25%. Separately, Oran Berry 6%')
);
out.push(
  row(
    'Small chest',
    '4 to 7 coins, Oran Berry or magnet (50/50), Sitrus Berry, 20 XP, ' + pct(chestItem) + ' chance of a Pokemon item'
  )
);
out.push(
  row(
    'Big chest',
    '9 coins, 1 to 3 tickets, 15% x10 ticket, ' +
      pct(bigItem) +
      ' chance of a Pokemon item, one ground item roll, one level of XP'
  )
);
out.push(row('XP orbs from rocks and chests', 'Also roll the wild extras above, like a kill'));
out.push('');
out.push('## Ground items (' + ground.length + ')');
out.push('');
out.push(
  'Chance columns are per wild kill (base ' +
    pct(wildGroundBase) +
    ' ground roll times the item weight, plus the direct Oran and Sitrus drops) and per elite (its guaranteed ground roll times the weight, plus its guaranteed berry). Pinaps raise the wild roll.'
);
out.push('');
out.push(row('Item', 'What it does', 'Weight', 'Per wild kill', 'Per elite'));
out.push(row('---', '---', '---', '---', '---'));
for (const g of ground)
  out.push(
    row(
      g.name,
      g.desc,
      pct(g.w / 100),
      pct((wildGroundBase * g.w) / 100 + direct('wild', g.id)),
      pct(g.w / 100 + direct('elite', g.id))
    )
  );
out.push('');
out.push('## Pokemon items (' + nP + ')');
out.push('');
out.push(
  'All Pokemon items are equally likely (1 in ' +
    nP +
    ' per Pokemon-item roll). Chance columns are per kill of that source.'
);
out.push('');
out.push(row('Item', 'What it does', 'Per elite', 'Per boss', 'Per gym leader', 'Per small chest', 'Per big chest'));
out.push(row('---', '---', '---', '---', '---', '---', '---'));
for (const i of poke)
  out.push(
    row(i.name, i.desc, pct(eliteItem / nP), pct((1 - bossRun) / nP), pct(gymP), pct(chestItem / nP), pct(bigItem / nP))
  );
out.push('');
out.push('## Run items (' + nR + ')');
out.push('');
out.push(
  'Only bosses and gym leaders drop them, and only ones the team does not already hold, so the chance of each rises as you hold more. Chance columns assume none held (1 in ' +
    nR +
    ' per run-item roll). Elites never drop them.'
);
out.push('');
out.push(row('Item', 'What it does', 'Group', 'Per boss', 'Per gym leader'));
out.push(row('---', '---', '---', '---', '---'));
for (const i of run) out.push(row(i.name, i.desc, i.group || '', pct(bossRun / nR), pct(gymRun / nR)));
out.push('');
out.push('## Other pickups (not items)');
out.push('');
out.push(row('Pickup', 'What it does'));
out.push(row('---', '---'));
out.push(
  row(
    'XP orb / big XP orb',
    'Experience; every kill drops one, an orb worth 5% of the next level or more draws as the big one'
  )
);
out.push(row('Coin', 'PokeCoins, banked at the end of the run (Amulet Coin: +50%)'));
out.push(row('Ticket / x10 ticket', 'Banked into Pokeball (x1) and Master Ball (x10) gacha tickets'));
out.push(
  row(
    'Heal pickup (retired)',
    'Used to heal 30% of max HP; nothing drops it any more, Oran and Sitrus Berry ground items replaced it everywhere'
  )
);
out.push(row('Magnet', 'Pulls every pickup on screen to the nearest player'));
out.push(
  row('Bomb', 'Screen clear: every wild enemy in view falls; bosses, gym leaders and elites take a hit instead')
);
out.push('');
const body = out.join('\n') + '\n';
const file = path.join(root, 'docs', 'ITEMS.md');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== body) {
    console.log('docs/ITEMS.md is out of date: run node tools/items_report.js');
    process.exit(1);
  }
  console.log('docs/ITEMS.md is current');
} else {
  fs.writeFileSync(file, body);
  console.log('wrote docs/ITEMS.md (' + ground.length + ' ground, ' + nP + ' pokemon, ' + nR + ' run items)');
}
