// tools/status_anims.js: bake the on-sprite status animations (#78, docs/HUD-STYLE.md "On-sprite status icons (#71)").
// Reads every assets/status/<key>.json (frame size, count, per-frame ms, anchor and pivot) and writes:
//   js/data/status-anims.js                       G.STATUS_ANIMS, the same layout as a script, since file:// cannot read JSON
//   assets/status/stats/stat-up-<stat>.png        stat-up streaks recoloured per stat (UI-PALETTES "Pokemon Stats")
//   assets/status/stats/stat-down-<stat>.png      stat-down streaks recoloured the same way
// The game cannot recolour pixels itself, since browsers block pixel reads of images opened from file:// (a tainted canvas).
// Run this after changing a sheet or its JSON in assets/status/.
// Usage: node tools/status_anims.js            write the data file and the stat sheets
//        node tools/status_anims.js --check    exit 1 if either is out of date (used by tools/check.js)
const fs = require('fs'),
  path = require('path'),
  zlib = require('zlib'),
  { readPng } = require('./gym_contact.js');
const root = path.resolve(__dirname, '..'),
  STATUS_DIR = path.join(root, 'assets/status'),
  STATS_DIR = path.join(STATUS_DIR, 'stats'),
  DATA_OUT = path.join(root, 'js/data/status-anims.js');

// UI-PALETTES "Pokemon Stats": [Light, Base, Dark] per stat, keyed by G.Stages.STATS.
const STAT_COLOURS = {
  atk: ['#F5DE69', '#EFCC18', '#9B8510'],
  def: ['#F09A65', '#E86412', '#97410C'],
  spa: ['#66D8F6', '#14C3F1', '#0D7F9D'],
  spd: ['#899EEA', '#4A6ADF', '#304591'],
  spe: ['#E46CCA', '#D51DAD', '#8B1370'],
};
// The streak art's own colours and the shade each takes: the yellow streaks become Light and Base, the orange-red ones
// Base and Dark, white stays white (HUD-STYLE "Stat colours").
const SOURCE_SHADES = { '#fff700': 0, '#deb500': 1, '#ff845a': 1, '#d63900': 2 };
const RECOLOURED_SHEETS = ['stat-up', 'stat-down'];

const hexOf = (red, green, blue) =>
  '#' + [red, green, blue].map((channel) => channel.toString(16).padStart(2, '0')).join('');
const rgbOf = (hex) => [1, 3, 5].map((start) => parseInt(hex.slice(start, start + 2), 16));

function readLayouts() {
  return fs
    .readdirSync(STATUS_DIR)
    .filter((name) => name.endsWith('.json'))
    .sort()
    .map((name) => JSON.parse(fs.readFileSync(path.join(STATUS_DIR, name), 'utf8')));
}

/** The sheet's pixels with each source streak colour swapped for the stat's shade, as a flat RGBA buffer. */
function recolouredPixels(sheetFile, stat) {
  const art = readPng(sheetFile),
    pixels = Buffer.alloc(art.w * art.h * 4),
    shades = STAT_COLOURS[stat].map(rgbOf);
  for (let y = 0; y < art.h; y++)
    for (let x = 0; x < art.w; x++) {
      const [red, green, blue, alpha] = art.rgba(x, y),
        shade = alpha ? SOURCE_SHADES[hexOf(red, green, blue)] : undefined,
        rgb = shade === undefined ? [red, green, blue] : shades[shade];
      pixels.set([...rgb, alpha], (y * art.w + x) * 4);
    }
  return { width: art.w, height: art.h, pixels };
}

// ---------- a minimal PNG writer (8-bit RGBA, no filter) ----------
const CRC_TABLE = Array.from({ length: 256 }, (_, index) => {
  let value = index;
  for (let bit = 0; bit < 8; bit++) value = value & 1 ? 0xedb88320 ^ (value >>> 1) : value >>> 1;
  return value >>> 0;
});
function crc32(bytes) {
  let crc = 0xffffffff;
  for (const byte of bytes) crc = CRC_TABLE[(crc ^ byte) & 255] ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
}
function pngChunk(type, data) {
  const length = Buffer.alloc(4),
    crc = Buffer.alloc(4),
    typeAndData = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  length.writeUInt32BE(data.length);
  crc.writeUInt32BE(crc32(typeAndData));
  return Buffer.concat([length, typeAndData, crc]);
}
function encodePng({ width, height, pixels }) {
  const header = Buffer.alloc(13);
  header.writeUInt32BE(width, 0);
  header.writeUInt32BE(height, 4);
  header.set([8, 6, 0, 0, 0], 8);
  const rows = Buffer.alloc((width * 4 + 1) * height);
  for (let y = 0; y < height; y++) pixels.copy(rows, y * (width * 4 + 1) + 1, y * width * 4, (y + 1) * width * 4);
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    pngChunk('IHDR', header),
    pngChunk('IDAT', zlib.deflateSync(rows, { level: 9 })),
    pngChunk('IEND', Buffer.alloc(0)),
  ]);
}

const statSheetPath = (key, stat) => 'assets/status/stats/' + key + '-' + stat + '.png';

function dataText(layouts) {
  const lines = [
    '// GENERATED by tools/status_anims.js from assets/status/*.json: do not edit by hand (edit the JSON and rerun it).',
    '// Each on-sprite status animation (#78, HUD-STYLE "On-sprite status icons"): its sheet (frames left to right), frame',
    '// size in art pixels, per-frame ms, the anchor it sits on (feet, body or head) and the art pixel that lands on it.',
    '// The stat sheets also list one pre-coloured sheet per stat.',
    'G.STATUS_ANIMS = {',
  ];
  for (const layout of layouts) {
    const entry = {
      image: 'assets/status/' + layout.image,
      frameWidth: layout.frameWidth,
      frameHeight: layout.frameHeight,
      frameMs: layout.frameMs,
      anchor: layout.anchor,
      pivot: layout.pivot,
    };
    if (RECOLOURED_SHEETS.includes(layout.status))
      entry.statImages = Object.fromEntries(
        Object.keys(STAT_COLOURS).map((stat) => [stat, statSheetPath(layout.status, stat)])
      );
    lines.push('  ' + JSON.stringify(layout.status) + ': ' + JSON.stringify(entry) + ',');
  }
  lines.push('};', '');
  return lines.join('\n');
}

function samePixels(file, expected) {
  if (!fs.existsSync(file)) return false;
  const art = readPng(file);
  if (art.w !== expected.width || art.h !== expected.height) return false;
  for (let y = 0; y < art.h; y++)
    for (let x = 0; x < art.w; x++) {
      const at = (y * art.w + x) * 4,
        actual = art.rgba(x, y);
      for (let channel = 0; channel < 4; channel++) if (actual[channel] !== expected.pixels[at + channel]) return false;
    }
  return true;
}

const layouts = readLayouts();
const text = dataText(layouts);
const statSheets = [];
for (const key of RECOLOURED_SHEETS) {
  const layout = layouts.find((entry) => entry.status === key);
  if (!layout) throw new Error('assets/status/' + key + '.json is missing');
  for (const stat of Object.keys(STAT_COLOURS))
    statSheets.push({
      file: path.join(root, statSheetPath(key, stat)),
      art: recolouredPixels(path.join(STATUS_DIR, layout.image), stat),
    });
}

if (process.argv.includes('--check')) {
  let stale = 0;
  const current = fs.existsSync(DATA_OUT) ? fs.readFileSync(DATA_OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== text) {
    console.log('STALE js/data/status-anims.js does not match assets/status/*.json (run node tools/status_anims.js)');
    stale++;
  }
  for (const sheet of statSheets)
    if (!samePixels(sheet.file, sheet.art)) {
      console.log('STALE ' + path.relative(root, sheet.file) + ' (run node tools/status_anims.js)');
      stale++;
    }
  if (stale) process.exit(1);
  console.log('status anims: current (' + layouts.length + ' animations, ' + statSheets.length + ' stat sheets)');
} else {
  fs.mkdirSync(STATS_DIR, { recursive: true });
  fs.writeFileSync(DATA_OUT, text);
  for (const sheet of statSheets) fs.writeFileSync(sheet.file, encodePng(sheet.art));
  console.log('wrote js/data/status-anims.js and ' + statSheets.length + ' stat sheets');
}
