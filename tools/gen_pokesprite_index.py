"""Generate js/data/pokesprite-index.js from assets/items/pokesprite-inventory.css.
Maps '<category>.<name>' -> [x, y] (top-left of its 32x32 cell in pokesprite-inventory.png), for the categories the game uses.
Usage (repo root): python tools/gen_pokesprite_index.py
"""
import re, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATS = {'ball', 'berry', 'battle-item', 'medicine', 'hold-item', 'evo-item', 'gem', 'plate', 'key-item', 'valuable-item', 'hm'}   # key-item / valuable-item / hm added for the main menu icons
rx = re.compile(r'^\.pokesprite\.([a-z0-9-]+)\.([a-z0-9-]+) \{ background-position: -(\d+)px -(\d+)px \}')
out = {}
for line in open(os.path.join(ROOT, 'assets/items/pokesprite-inventory.css'), encoding='utf-8'):
    m = rx.match(line)
    if m and m.group(1) in CATS:
        out[m.group(1) + '.' + m.group(2)] = [int(m.group(3)), int(m.group(4))]
body = json.dumps(out, separators=(',', ':'), sort_keys=True)
with open(os.path.join(ROOT, 'js/data/pokesprite-index.js'), 'w', encoding='utf-8') as f:
    f.write('/* GENERATED by tools/gen_pokesprite_index.py from assets/items/pokesprite-inventory.css, do not edit.\n'
            ' * "<category>.<name>": [x, y] of the 32x32 cell in assets/items/pokesprite-inventory.png (2174 x 576).\n'
            ' * Used by G.Icons through "ps:<category>.<name>". */\n')
    f.write('G.PokeSprite = ' + body + ';\n')
print(len(out), 'sprites')
