// tools/species_traits.js: regenerates js/data/species-traits.js (what G.Copies rolls a Pokemon copy from) from pokeapi and js/data/pokedex.js.
// One row per species in the game: gender rate, ability names by slot, height, weight, base friendship. Plus the 25 natures.
// Usage from the repo root:  node tools/species_traits.js          (writes js/data/species-traits.js)
//                            node tools/species_traits.js --check  (exit 1 if the file is out of date)
const fs = require('fs'),
  path = require('path');
const root = path.resolve(__dirname, '..');
const OUT = path.join(root, 'js', 'data', 'species-traits.js');
const csv = (name) => {
  const lines = fs
    .readFileSync(path.join(root, 'pokeapi-master', 'data', 'v2', 'csv', name), 'utf8')
    .trim()
    .split(/\r?\n/);
  const head = lines[0].split(',');
  return lines.slice(1).map((l) => {
    const cols = l.split(','),
      row = {};
    head.forEach((h, i) => (row[h] = cols[i]));
    return row;
  });
};

const dexes = [
  ...new Set(
    [...fs.readFileSync(path.join(root, 'js', 'data', 'pokedex.js'), 'utf8').matchAll(/"dex":(\d+)/g)].map((m) => +m[1])
  ),
].sort((a, b) => a - b);
const species = new Map(csv('pokemon_species.csv').map((r) => [+r.id, r]));
const pokemon = new Map(csv('pokemon.csv').map((r) => [+r.id, r]));
const abilityName = new Map(csv('abilities.csv').map((r) => [r.id, r.identifier]));
const englishName = new Map(
  csv('ability_names.csv')
    .filter((r) => r.local_language_id === '9')
    .map((r) => [r.ability_id, r.name])
);
const abilityId = new Map(csv('abilities.csv').map((r) => [r.identifier, r.id]));
const abilities = new Map();
for (const r of csv('pokemon_abilities.csv')) {
  if (!abilities.has(+r.pokemon_id)) abilities.set(+r.pokemon_id, [null, null, null]);
  abilities.get(+r.pokemon_id)[+r.slot - 1] = abilityName.get(r.ability_id);
}

const rows = dexes.map((dex) => {
  const s = species.get(dex),
    p = pokemon.get(dex),
    a = abilities.get(dex);
  if (!s || !p || !a) throw new Error('no pokeapi data for dex ' + dex);
  return `  ${dex}: [${+s.gender_rate}, ${JSON.stringify(a)}, ${+p.height}, ${+p.weight}, ${+s.base_happiness}],`;
});
// Stat positions are the game's stats array order: pokeapi stat id minus 1 (HP, Atk, Def, SpA, SpD, Spe).
const natures = csv('natures.csv')
  .sort((a, b) => a.id - b.id)
  .map((r) => `  ${JSON.stringify([r.identifier, r.increased_stat_id - 1, r.decreased_stat_id - 1])},`);

const used = [...new Set(dexes.flatMap((d) => abilities.get(d)).filter(Boolean))].sort();
const abilityNames = used.map((id) => {
  const name = englishName.get(abilityId.get(id));
  if (!name) throw new Error('no English name for ability ' + id);
  return `  ${JSON.stringify(id)}: ${JSON.stringify(name)},`;
});

const body = [
  '/* ============ species-traits.js, what a Pokemon copy is rolled from (G.Copies) ============',
  ' * GENERATED by tools/species_traits.js from pokeapi and js/data/pokedex.js. Do not edit by hand.',
  ' * SPECIES: dex -> [gender rate (female chance out of 8, -1 genderless), [ability slot 1, slot 2, hidden], height in',
  ' * decimetres, weight in hectograms, base friendship]. NATURES: pokeapi id minus 1 -> [name, raised stat, lowered stat], where',
  ' * the stat is a position in the stats array (HP, Atk, Def, SpA, SpD, Spe) and raised = lowered means neutral.',
  ' * ABILITY_NAMES: ability id -> English name.',
  ' */',
  'G.SpeciesTraits = {',
  '  SPECIES: {',
  ...rows.map((r) => '  ' + r),
  '  },',
  '  NATURES: [',
  ...natures.map((r) => '  ' + r),
  '  ],',
  '  ABILITY_NAMES: {',
  ...abilityNames.map((r) => '  ' + r),
  '  },',
  '};',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== body) {
    console.log('js/data/species-traits.js is out of date: run node tools/species_traits.js');
    process.exit(1);
  }
  console.log('js/data/species-traits.js is current (' + rows.length + ' species)');
} else {
  fs.writeFileSync(OUT, body);
  console.log('wrote js/data/species-traits.js (' + rows.length + ' species)');
}
