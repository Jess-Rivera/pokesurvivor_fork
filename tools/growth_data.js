// tools/growth_data.js: regenerates js/data/growth-curves.js (#139 8a: Exp Candy levels) from pokeapi.
// It writes the six mainline XP curves (experience.csv), each species' curve (pokemon_species.csv growth_rate_id), and
// the lowest level among a species' level-up evolutions (pokemon_evolution.csv, trigger 1 with a minimum_level).
// Usage from the repo root:  node tools/growth_data.js          (writes js/data/growth-curves.js)
//                            node tools/growth_data.js --check  (exit 1 if the file is out of date)
const fs = require('fs'),
  path = require('path');
const root = path.resolve(__dirname, '..');
const OUT = path.join(root, 'js', 'data', 'growth-curves.js');
const CSV_DIR = path.join(root, 'pokeapi-master', 'data', 'v2', 'csv');
const LEVEL_UP_TRIGGER = '1'; // evolution_triggers.csv: 1 is level-up
const MAX_LEVEL = 100;

/** A pokeapi CSV as a list of { column: text } rows. */
function readCsv(name) {
  const lines = fs.readFileSync(path.join(CSV_DIR, name), 'utf8').trim().split(/\r?\n/);
  const header = lines[0].split(',');
  return lines.slice(1).map((line) => {
    const cells = line.split(',');
    const row = {};
    header.forEach((column, index) => (row[column] = cells[index]));
    return row;
  });
}

const species = readCsv('pokemon_species.csv');
const experience = readCsv('experience.csv');
const evolutions = readCsv('pokemon_evolution.csv');

// growth rate id -> the XP total at levels 1 to 100
const curves = {};
for (const row of experience) {
  const list = (curves[row.growth_rate_id] = curves[row.growth_rate_id] || []);
  list[+row.level - 1] = +row.experience;
}
for (const id of Object.keys(curves))
  if (curves[id].length !== MAX_LEVEL || curves[id].some((xp) => !Number.isFinite(xp)))
    throw new Error('experience.csv: growth rate ' + id + ' does not cover levels 1 to ' + MAX_LEVEL);

// one character per dex (dex 1 is the first), the species' growth rate id
const maxDex = Math.max(...species.map((row) => +row.id));
const rateByDex = new Array(maxDex).fill('0');
for (const row of species) {
  if (!curves[row.growth_rate_id] || row.growth_rate_id.length !== 1)
    throw new Error('pokemon_species.csv: ' + row.identifier + ' has an unknown growth rate ' + row.growth_rate_id);
  rateByDex[+row.id - 1] = row.growth_rate_id;
}

// the level of each level-up evolution, then per pre-evolution the lowest of its evolutions' levels
const fromOf = {};
for (const row of species) if (row.evolves_from_species_id) fromOf[row.id] = +row.evolves_from_species_id;
const nextLevel = {};
for (const row of evolutions) {
  if (row.evolution_trigger_id !== LEVEL_UP_TRIGGER || !row.minimum_level) continue;
  const from = fromOf[row.evolved_species_id];
  if (!from) continue;
  const level = +row.minimum_level;
  if (nextLevel[from] == null || level < nextLevel[from]) nextLevel[from] = level;
}
const nextLevelText = Object.keys(nextLevel)
  .map(Number)
  .sort((a, b) => a - b)
  .map((dex) => dex + ':' + nextLevel[dex])
  .join(',');

const curveText = Object.keys(curves)
  .sort()
  .map((id) => '    ' + id + ': [' + curves[id].join(',') + '],')
  .join('\n');

const body = [
  '/* ============ growth-curves.js, the mainline XP curves (G.GrowthCurves; #139 8a Exp Candy) ============',
  ' * GENERATED by tools/growth_data.js from pokeapi experience.csv, pokemon_species.csv and pokemon_evolution.csv.',
  ' * Do not edit by hand. CURVES: growth rate id -> the XP total at levels 1 to 100. RATE: one growth rate id per',
  ' * dex (dex 1 first). NEXT_LEVEL: dex -> the lowest level among its level-up evolutions (absent: it has none).',
  ' */',
  'G.GrowthCurves = (() => {',
  '  const MAX_LEVEL = ' + MAX_LEVEL + ';',
  '  const CURVES = {',
  curveText,
  '  };',
  "  const RATE = '" + rateByDex.join('') + "';",
  '  const NEXT_LEVEL = {' + nextLevelText + '};',
  '  /** The XP totals at levels 1 to 100 of a species, or null for a dex pokeapi does not have. */',
  '  const curveOf = (dex) => CURVES[RATE[dex - 1]] || null;',
  '  /** The lowest level among its level-up evolutions, or null when it has none. */',
  '  const nextEvolutionLevel = (dex) => NEXT_LEVEL[dex] || null;',
  '  return { MAX_LEVEL, curveOf, nextEvolutionLevel };',
  '})();',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== body) {
    console.log('js/data/growth-curves.js is out of date: run node tools/growth_data.js');
    process.exit(1);
  }
  console.log('js/data/growth-curves.js is current (' + maxDex + ' species)');
} else {
  fs.writeFileSync(OUT, body);
  console.log('wrote js/data/growth-curves.js (' + maxDex + ' species)');
}
