// tools/evolvable_data.js: regenerates js/data/evolvable.js (the species that can still evolve, for Eviolite) from pokeapi pokemon_species.csv.
// A species can still evolve when another species names it in evolves_from_species_id. pokedex.js has no evolution data and is generated bulk.
// Usage from the repo root:  node tools/evolvable_data.js          (writes js/data/evolvable.js)
//                            node tools/evolvable_data.js --check  (exit 1 if the file is out of date)
const fs = require('fs'),
  path = require('path');
const root = path.resolve(__dirname, '..');
const OUT = path.join(root, 'js', 'data', 'evolvable.js');
const lines = fs
  .readFileSync(path.join(root, 'pokeapi-master', 'data', 'v2', 'csv', 'pokemon_species.csv'), 'utf8')
  .trim()
  .split(/\r?\n/);
const col = lines[0].split(',').indexOf('evolves_from_species_id');
if (col < 0) throw new Error('pokemon_species.csv: no evolves_from_species_id column');
const ids = [...new Set(lines.slice(1).map((l) => +l.split(',')[col]))].filter((n) => n > 0).sort((a, b) => a - b);
const body = [
  '/* ============ evolvable.js, the species that can still evolve (Eviolite) ============',
  ' * GENERATED by tools/evolvable_data.js from pokeapi pokemon_species.csv. Do not edit by hand.',
  ' */',
  'G.Evolvable = (() => {',
  '  const IDS = new Set([' + ids.join(',') + ']);',
  '  return { has: (dex) => IDS.has(dex) };',
  '})();',
  '',
].join('\n');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== body) {
    console.log('js/data/evolvable.js is out of date: run node tools/evolvable_data.js');
    process.exit(1);
  }
  console.log('js/data/evolvable.js is current (' + ids.length + ' species)');
} else {
  fs.writeFileSync(OUT, body);
  console.log('wrote js/data/evolvable.js (' + ids.length + ' species)');
}
