// tools/stage_one_data.js: regenerates js/data/stage-one.js (the Stage 1 species, for the rescue pool) from pokeapi pokemon_species.csv.
// Stage 1 = a species with no pre-evolution (empty evolves_from_species_id); babies count (Pichu is Stage 1, Pikachu is not).
// EXCEPTIONS count as Stage 1 although the csv names a pre-evolution: the pre-evolution is not in the game (acquisition spec R5,
// Gholdengo only; Accelgor is NOT one, it comes from Karrablast with a Shed Shell). pokedex.js has no evolution data.
// Usage from the repo root:  node tools/stage_one_data.js          (writes js/data/stage-one.js)
//                            node tools/stage_one_data.js --check  (exit 1 if the file is out of date)
const fs = require('fs'),
  path = require('path');
const root = path.resolve(__dirname, '..');
const OUT = path.join(root, 'js', 'data', 'stage-one.js');
const EXCEPTIONS = [1000]; // Gholdengo (Gimmighoul has no sprites)
const lines = fs
  .readFileSync(path.join(root, 'pokeapi-master', 'data', 'v2', 'csv', 'pokemon_species.csv'), 'utf8')
  .trim()
  .split(/\r?\n/);
const header = lines[0].split(',');
const idCol = header.indexOf('id'),
  fromCol = header.indexOf('evolves_from_species_id');
if (idCol < 0 || fromCol < 0) throw new Error('pokemon_species.csv: no id or evolves_from_species_id column');
const ids = lines
  .slice(1)
  .map((l) => l.split(','))
  .filter((c) => !c[fromCol])
  .map((c) => +c[idCol])
  .concat(EXCEPTIONS);
const sorted = [...new Set(ids)].sort((a, b) => a - b);
const body = [
  '/* ============ stage-one.js, the Stage 1 species (the rescue pool) ============',
  ' * GENERATED by tools/stage_one_data.js from pokeapi pokemon_species.csv. Do not edit by hand.',
  ' * No pre-evolution (babies included), plus Gholdengo as the one species whose pre-evolution is not in the game.',
  ' */',
  'G.StageOne = (() => {',
  '  const IDS = new Set([' + sorted.join(',') + ']);',
  '  return { has: (dex) => IDS.has(dex) };',
  '})();',
  '',
].join('\n');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== body) {
    console.log('js/data/stage-one.js is out of date: run node tools/stage_one_data.js');
    process.exit(1);
  }
  console.log('js/data/stage-one.js is current (' + sorted.length + ' species)');
} else {
  fs.writeFileSync(OUT, body);
  console.log('wrote js/data/stage-one.js (' + sorted.length + ' species)');
}
