// tools/library_doc_colours.js: copies every colour the style docs list into tools/library/doc-colours.js, for the
// library board's "Style docs" colours tab (#155 155a). A page opened from disk cannot read the .md files, so the board
// reads this copy; check.js runs this with --check, which fails when the copy is out of date.
// Sources: docs/HUD-STYLE.md "Colour palette" (up to "Shapes", as smoke-ui-library reads it) and docs/UI-PALETTES.md.
// Usage: node tools/library_doc_colours.js            (writes the file)
//        node tools/library_doc_colours.js --check    (exit 1 if the file differs from the docs)
const fs = require('fs'),
  path = require('path');
const root = path.resolve(__dirname, '..');
const OUT = path.join(root, 'tools', 'library', 'doc-colours.js');
const CHECK = process.argv.includes('--check');

// Six-digit hexes only: the docs also cite issue numbers like #104, which would read as three-digit colours.
const HEX = /#[0-9a-f]{6}\b/gi;

/** Plain text of a Markdown line or heading: no tags, marks, links or table pipes. */
function plainText(line) {
  return line
    .replace(/^#+\s*/, '')
    .replace(/`\[(Approved|Proposed|Open|Legacy behavior)\]`\s*/g, '')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/[`*]/g, '')
    .replace(/^\s*[-|]\s*/, '')
    .replace(/\s*\|\s*$/, '')
    .replace(/\s*\|\s*/g, ' | ')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Every colour in a doc's text, once per section: { doc, section, hex, line }. */
function coloursIn(doc, text) {
  const found = [],
    seen = new Set();
  let section = doc;
  for (const line of text.split(/\r?\n/)) {
    if (/^#{2,5}\s/.test(line)) section = plainText(line);
    for (const match of line.match(HEX) || []) {
      const hex = match.toLowerCase(),
        key = section + '|' + hex;
      if (seen.has(key)) continue;
      seen.add(key);
      found.push({ doc, section, hex, line: plainText(line) });
    }
  }
  return found;
}

const hudStyle = fs.readFileSync(path.join(root, 'docs', 'HUD-STYLE.md'), 'utf8');
const paletteStart = hudStyle.indexOf('\n## Colour palette'),
  paletteEnd = hudStyle.indexOf('\n## Shapes', paletteStart);
if (paletteStart < 0 || paletteEnd < 0) {
  console.log('FAIL docs/HUD-STYLE.md has no "Colour palette" section before "Shapes"');
  process.exit(1);
}
const colours = [
  ...coloursIn('HUD-STYLE.md', hudStyle.slice(paletteStart, paletteEnd)),
  ...coloursIn('UI-PALETTES.md', fs.readFileSync(path.join(root, 'docs', 'UI-PALETTES.md'), 'utf8')),
];

const body =
  '// tools/library/doc-colours.js: GENERATED by tools/library_doc_colours.js from docs/HUD-STYLE.md "Colour palette"\n' +
  '// and docs/UI-PALETTES.md. Do not edit; rerun the tool after changing either doc.\n' +
  '/* global window */\n' +
  'window.LIBRARY_DOC_COLOURS = ' +
  JSON.stringify(colours, null, 1) +
  ';\n';

const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
if (CHECK) {
  if (current !== body) {
    console.log('FAIL tools/library/doc-colours.js is out of date: run node tools/library_doc_colours.js');
    process.exit(1);
  }
  console.log('library doc colours: current (' + colours.length + ' entries)');
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, body);
  console.log('library doc colours: wrote ' + colours.length + ' entries');
}
